export const OUTLINE_NAMES = Object.keys(cookiecutters.outlines);

export function getOutline(name) {
  const o = cookiecutters.outlines[name];
  if (!o) return null;
  return {
    name,
    startPoint: o.startPoint ? o.startPoint.slice() : [0, 0],
    startAngle: o.startAngle ?? 0,
    turtlePath: o.turtlePath.map(([l, a]) => [l, a]),
  };
}
