/**
 * Arc stream to G-code, and the same walk as a preview mesh.
 *
 * The block is a 2D path. Z comes from the printer:
 *   z(s) = z0 + pitch * s
 * pitch 0 is one flat layer at z0. A cam weave uses pitch = height / length.
 *
 * Curves are sampled into G1s (max step `seg` mm). Straight arcs are one G1.
 */

const FILAMENT_AREA = (d) => Math.PI * (d / 2) ** 2;

export function printerDefaults(over = {}) {
  return {
    name: "generic",
    nozzle: 0.4,
    layer: 0.2,
    filament: 1.75,
    flow: 1,
    speed: 1800,
    travel: 6000,
    temp: 200,
    bed: 60,
    fan: 255,
    z0: 0.2,
    pitch: 0,
    seg: 1,
    width: 0.45,
    start: null,
    end: null,
    ...over,
  };
}

function startText(p) {
  if (p.start) return p.start;
  return [
    "; generated by arc turtle",
    "G21",
    "G90",
    "M82",
    `M104 S${p.temp}`,
    `M140 S${p.bed}`,
    `M190 S${p.bed}`,
    `M109 S${p.temp}`,
    "G28",
    "G92 E0",
    p.fan ? `M106 S${p.fan}` : "M107",
  ].join("\n");
}

function endText(p) {
  if (p.end) return p.end;
  return ["G92 E0", "M104 S0", "M140 S0", "M107", "G28 X0", "M84"].join("\n");
}

/** Advance a pose [x, y, heading] by one arc. Mutates and returns it. */
export function stepPose(pose, s, dtheta) {
  const th = pose[2];
  const ang = dtheta || 0;
  if (Math.abs(ang) < 1e-12) {
    pose[0] += s * Math.cos(th);
    pose[1] += s * Math.sin(th);
    return pose;
  }
  const half = ang / 2;
  const chord = (s * Math.sin(half)) / half;
  const mid = th + half;
  pose[0] += chord * Math.cos(mid);
  pose[1] += chord * Math.sin(mid);
  pose[2] += ang;
  return pose;
}

function fmt(n) {
  return (Math.round(n * 1000) / 1000).toFixed(3);
}

/**
 * Sample one arc into points in the current pose frame, then step the pose.
 * Yields {x, y, z, e, travel} with e advanced by extruded length.
 */
function* arcSamples(pose, s, da, p, state) {
  const len = Math.abs(s);
  const travel = len < 1e-9;
  const n = travel || Math.abs(da) < 1e-9 ? 1 : Math.max(1, Math.ceil(len / (p.seg || 1)));
  const ds = s / n;
  const dda = da / n;
  const area = (p.width || p.nozzle) * (p.layer || 0.2) * (p.flow || 1);
  const ePer = area / FILAMENT_AREA(p.filament || 1.75);
  for (let i = 0; i < n; i++) {
    stepPose(pose, ds, dda);
    const dist = state.s + Math.abs(ds);
    state.s = dist;
    if (!travel) state.e += Math.abs(ds) * ePer;
    const z = (p.z0 ?? p.layer ?? 0.2) + (p.pitch || 0) * state.s;
    yield { x: pose[0], y: pose[1], z, e: state.e, travel, f: travel ? p.travel : p.speed };
  }
}

/** G-code lines for one block. Does not retain the file. */
export function* gcodeLines(block, printer = {}) {
  const p = printerDefaults(printer);
  yield startText(p);
  const pose = [0, 0, 0];
  const state = { s: 0, e: 0 };
  let prevTravel = true;
  for (const [s, da] of block.arcs()) {
    for (const pt of arcSamples(pose, s, da, p, state)) {
      const words = [`G1 X${fmt(pt.x)} Y${fmt(pt.y)} Z${fmt(pt.z)}`];
      if (!pt.travel) words.push(`E${fmt(pt.e)}`);
      if (pt.travel !== prevTravel) words.push(`F${Math.round(pt.f || p.speed)}`);
      prevTravel = pt.travel;
      yield words.join(" ");
    }
  }
  yield endText(p);
}

/** Totals without keeping the lines. */
export function gcodeStats(block, printer = {}) {
  const p = printerDefaults(printer);
  let length = 0;
  let extrude = 0;
  for (const [s] of block.arcs()) {
    const len = Math.abs(s);
    length += len;
    if (len > 1e-9) extrude += len;
  }
  const area = (p.width || p.nozzle) * (p.layer || 0.2) * (p.flow || 1);
  const filament = (extrude * area) / FILAMENT_AREA(p.filament || 1.75);
  const minutes = extrude / (p.speed || 1800);
  return { length, extrude, filament, minutes, layers: p.pitch ? (p.pitch * length) / (p.layer || 0.2) : 1 };
}

/**
 * Triangle mesh of the path as a rectangular tube.
 * Corners are ±width/2 along the in-plane normal and ±height/2 along Z.
 * Returns { vertices: Float32Array, indices: Uint32Array } with stride 6
 * (xyz + normal).
 */
export function tubeMesh(block, printer = {}) {
  const p = printerDefaults(printer);
  const w = (p.width || p.nozzle || 0.4) / 2;
  const h = (p.layer || 0.2) / 2;
  const pose = [0, 0, 0];
  const state = { s: 0, e: 0 };
  const rings = [];
  rings.push(ringAt(pose, (p.z0 ?? 0.2), w, h));
  for (const [s, da] of block.arcs()) {
    for (const pt of arcSamples(pose, s, da, p, state)) {
      if (!pt.travel) rings.push(ringAt(pose, pt.z, w, h));
    }
  }
  return loft(rings);
}

function ringAt(pose, z, w, h) {
  const c = Math.cos(pose[2]);
  const s = Math.sin(pose[2]);
  const nx = -s;
  const ny = c;
  return [
    [pose[0] + nx * w, pose[1] + ny * w, z + h],
    [pose[0] - nx * w, pose[1] - ny * w, z + h],
    [pose[0] - nx * w, pose[1] - ny * w, z - h],
    [pose[0] + nx * w, pose[1] + ny * w, z - h],
  ];
}

function loft(rings) {
  const verts = [];
  const idx = [];
  const push = (x, y, z, nx, ny, nz) => {
    verts.push(x, y, z, nx, ny, nz);
    return verts.length / 6 - 1;
  };
  for (let i = 0; i < rings.length - 1; i++) {
    const a = rings[i];
    const b = rings[i + 1];
    for (let k = 0; k < 4; k++) {
      const k1 = (k + 1) % 4;
      const ax = a[k][0], ay = a[k][1], az = a[k][2];
      const bx = b[k][0], by = b[k][1], bz = b[k][2];
      const cx = a[k1][0], cy = a[k1][1], cz = a[k1][2];
      const ux = bx - ax, uy = by - ay, uz = bz - az;
      const vx = cx - ax, vy = cy - ay, vz = cz - az;
      let nx = uy * vz - uz * vy;
      let ny = uz * vx - ux * vz;
      let nz = ux * vy - uy * vx;
      const len = Math.hypot(nx, ny, nz) || 1;
      nx /= len;
      ny /= len;
      nz /= len;
      const i0 = push(ax, ay, az, nx, ny, nz);
      const i1 = push(bx, by, bz, nx, ny, nz);
      const i2 = push(cx, cy, cz, nx, ny, nz);
      const i3 = push(b[k1][0], b[k1][1], b[k1][2], nx, ny, nz);
      idx.push(i0, i1, i2, i1, i3, i2);
    }
  }
  return {
    vertices: new Float32Array(verts),
    indices: new Uint32Array(idx),
  };
}

/** Write an iterator of lines to a file. Streams when the browser allows it. */
export async function downloadLines(name, lines) {
  if (typeof window !== "undefined" && window.showSaveFilePicker) {
    const handle = await window.showSaveFilePicker({
      suggestedName: name,
      types: [{ description: "G-code", accept: { "text/plain": [".gcode"] } }],
    });
    const writable = await handle.createWritable();
    for (const line of lines) await writable.write(line + "\n");
    await writable.close();
    return "saved";
  }
  const parts = [];
  for (const line of lines) parts.push(line + "\n");
  const blob = new Blob(parts, { type: "text/plain" });
  const file = new File([blob], name, { type: "text/plain" });
  if (navigator.share && navigator.canShare && navigator.canShare({ files: [file] })) {
    await navigator.share({ files: [file], title: name });
    return "shared";
  }
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = name;
  a.click();
  URL.revokeObjectURL(a.href);
  return "downloaded";
}
